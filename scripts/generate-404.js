/**
 * Generates public/404.html for the GitHub Pages SPA-routing fix, with
 * pathSegmentsToKeep computed automatically from VITE_BASE_PATH so it
 * always matches the actual deployed base — no manual editing required.
 * https://github.com/rafgraph/spa-github-pages
 */
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const basePath = process.env.VITE_BASE_PATH || '/';
const pathSegmentsToKeep = basePath.split('/').filter(Boolean).length;

const html = `<!doctype html>
<!--
  Auto-generated by scripts/generate-404.js — do not edit by hand.
  Regenerated on every build from the current base path ("${basePath}").
  GitHub Pages serves this file for any unknown path; it redirects back to
  index.html while preserving the original URL, so React Router can render
  the right page. https://github.com/rafgraph/spa-github-pages
-->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>Subechhya Bag पसल</title>
    <script>
      var pathSegmentsToKeep = ${pathSegmentsToKeep};

      var l = window.location;
      l.replace(
        l.protocol +
          '//' +
          l.hostname +
          (l.port ? ':' + l.port : '') +
          l.pathname
            .split('/')
            .slice(0, 1 + pathSegmentsToKeep)
            .join('/') +
          '/?/' +
          l.pathname.slice(1).split('/').slice(pathSegmentsToKeep).join('/').replace(/&/g, '~and~') +
          (l.search ? '&' + l.search.slice(1).replace(/&/g, '~and~') : '') +
          l.hash
      );
    </script>
  </head>
  <body></body>
</html>
`;

writeFileSync(path.join(root, 'public/404.html'), html, 'utf-8');

console.log(
  `✔ 404.html generated (base "${basePath}", pathSegmentsToKeep=${pathSegmentsToKeep})`
);
